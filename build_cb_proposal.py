def _font(run, size=None, bold=False, color=None, italic=False):
    run.font.name = FONT; run.bold = bold; run.italic = italic
    if size: run.font.size = Pt(size)
    if color is not None: run.font.color.rgb = color
    rF = run._element.get_or_add_rPr().get_or_add_rFonts()
    for a in ("w:eastAsia", "w:ascii", "w:hAnsi"): rF.set(qn(a), FONT)

def para(text="", size=10.5, bold=False, color=None, align=None, space_after=6, space_before=0, italic=False):
    p = doc.add_paragraph()
    if align is not None: p.alignment = align
    p.paragraph_format.space_after = Pt(space_after); p.paragraph_format.space_before = Pt(space_before)
    if text: _font(p.add_run(text), size, bold, color, italic)
    return p

def runs_para(parts, size=10.5, align=None, space_after=6, space_before=0):
    p = doc.add_paragraph()
    if align is not None: p.alignment = align
    p.paragraph_format.space_after = Pt(space_after); p.paragraph_format.space_before = Pt(space_before)
    for t, b in parts: _font(p.add_run(t), size, b)
    return p

def heading(text, size=14):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14); p.paragraph_format.space_after = Pt(6)
    _font(p.add_run(text), size, True, NAVY)
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr"); bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single"); bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "4"); bottom.set(qn("w:color"), "12A06D")
    pbdr.append(bottom); pPr.append(pbdr)
    return p

def subheading(text, size=11.5):
    return para(text, size=size, bold=True, color=NAVY, space_before=8, space_after=4)

def bullets(items, size=10.5):
    for it in items:
        p = doc.add_paragraph(style="List Bullet"); p.paragraph_format.space_after = Pt(3)
        if isinstance(it, str):
            _font(p.add_run(it), size)
        elif isinstance(it, tuple) and all(isinstance(x, tuple) for x in it):
            for t, b in it: _font(p.add_run(t), size, b)
        else:  # tuple like ("text",) or ("text", bold)
            txt = it[0]; bold = it[1] if len(it) > 1 and isinstance(it[1], bool) else False
            _font(p.add_run(txt), size, bold)

def _shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), fill)
    tcPr.append(shd)

def _cell(cell, text, bold=False, color=None, size=10, align=None):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(2); p.paragraph_format.space_before = Pt(2)
    if align is not None: p.alignment = align
    for i, ln in enumerate(str(text).split("\n")):
        if i > 0:
            p = cell.add_paragraph()
            p.paragraph_format.space_after = Pt(2); p.paragraph_format.space_before = Pt(0)
            if align is not None: p.alignment = align
        _font(p.add_run(ln), size, bold, color)

def table(headers, rows, widths=None, size=10, header_dark=True, alt=True):
    ncol = len(headers)
    t = doc.add_table(rows=1, cols=ncol); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hc = t.rows[0].cells
    for i, h in enumerate(headers):
        _cell(hc[i], h, bold=True, color=RGBColor(0xff,0xff,0xff) if header_dark else NAVY, size=size)
        _shade(hc[i], HDR_FILL if header_dark else BOX_FILL)
    for r_i, row in enumerate(rows):
        cells = t.add_row().cells
        for i, val in enumerate(row):
            _cell(cells[i], val, bold=(i==0 and ncol>1), size=size)
            if alt and r_i % 2 == 1: _shade(cells[i], ALT_FILL)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows: row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def callout(title, body_lines, fill=BOX_FILL):
    t = doc.add_table(rows=1, cols=1); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.rows[0].cells[0]; _shade(c, fill); c.text = ""
    p = c.paragraphs[0]; p.paragraph_format.space_after = Pt(4)
    _font(p.add_run(title), 11, True, NAVY)
    for ln in body_lines:
        pp = c.add_paragraph(); pp.paragraph_format.space_after = Pt(3)
        if isinstance(ln, tuple) and len(ln) == 2 and isinstance(ln[1], bool):
            _font(pp.add_run(ln[0]), 10, ln[1])
        elif isinstance(ln, tuple):
            for tx, b in ln: _font(pp.add_run(tx), 10, b)
        else: _font(pp.add_run(ln), 10)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

