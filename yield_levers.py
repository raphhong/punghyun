# 취급 100(3개월 투입자본) 기준 사이클당·연환산 자본수익률 + 레버별 민감도
def cyc(E14=0.05,E15=1.225,E16=0.8,E18=1.0,E17=1.0,E19=0.075,E20=0.025,E25=0.003,E13=3):
    M = E16*E15 + (1-E16)*(E14*E13 + E18/E17)
    rev = 100*M + 100*E25
    cost = 100 + rev*E19 + 100*E20 + 100*0.005   # 매입+유동화+대손+지급수수료
    profit = rev - cost                 # 판관비 전 사이클 이익 (per 100 자본, 3개월)
    q = profit/100                       # 분기 수익률(자본 대비)
    cycles = 12/E13
    ann = (1+q)**cycles - 1              # 복리 연환산
    return M, profit, q, ann

def show(name, **kw):
    M,p,q,ann = cyc(**kw)
    print('%-34s M=%.3f 사이클이익=%5.2f 분기ROIC=%5.1f%% 연환산=%5.1f%%'%(name,M,p,q*100,ann*100))

print('== 기준(NEW BM) ==')
show('BASE 시가매입')
print('\n== 개별 레버 ==')
show('①렌탈료 5%→7.5%/월', E14=0.075)
show('②할부회수 1.225→1.25 [법적주의]', E15=1.25)
show('③잔존가치 매각 100%→105% [안전]', E18=1.05)
show('④잔존가치 매각 100%→110% [안전]', E18=1.10)
show('⑤할부비율 80%→90%', E16=0.9)
show('⑥유동화 7.5%→5.0% [조달개선]', E19=0.05)
show('⑦대손 2.5%→1.5% [심사고도화]', E20=0.015)
show('⑧회전 3개월→2개월 [속도]', E13=2)
print('\n== 조합: 안전한 레버만 (재매각105%+유동화5%+대손1.5%) ==')
show('SAFE COMBO', E18=1.05, E19=0.05, E20=0.015)
print('\n== 조합: 공격적(+렌탈7.5%+할부90%+회전2.5M) ==')
show('AGGR COMBO', E14=0.075,E16=0.9,E18=1.05,E19=0.05,E20=0.015,E13=2.5)
