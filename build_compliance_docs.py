KFONT = '맑은 고딕'
NAVY = RGBColor(0x14, 0x24, 0x3B)
GREEN = RGBColor(0x1F, 0x5C, 0x4D)
GREY = RGBColor(0x55, 0x55, 0x55)

def base_doc():
    doc = Document()
    st = doc.styles['Normal']
    st.font.name = KFONT
    st.font.size = Pt(10)
    st.element.rPr.rFonts.set(qn('w:eastAsia'), KFONT)
    return doc

def _setfont(run, size=None, bold=None, color=None, name=KFONT):
    run.font.name = name
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rpr.insert(0, rf)
    rf.set(qn('w:eastAsia'), name)
    if size is not None: run.font.size = Pt(size)
    if bold is not None: run.font.bold = bold
    if color is not None: run.font.color.rgb = color

def title(doc, text, sub=None):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = p.add_run(text); _setfont(r, 18, True, NAVY)
    p.paragraph_format.space_after = Pt(2)
    if sub:
        p2 = doc.add_paragraph(); r2 = p2.add_run(sub); _setfont(r2, 10, False, GREY)
        p2.paragraph_format.space_after = Pt(10)

def h1(doc, text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(4)
    r = p.add_run(text); _setfont(r, 13, True, GREEN)
    return p

def h2(doc, text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(8); p.paragraph_format.space_after = Pt(3)
    r = p.add_run(text); _setfont(r, 11, True, NAVY)
    return p

def para(doc, text, size=10, bold=False, color=None, after=6, before=0):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after); p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing = 1.3
    r = p.add_run(text); _setfont(r, size, bold, color)
    return p

def bullet(doc, text, size=10):
    p = doc.add_paragraph(style=None)
    p.paragraph_format.left_indent = Cm(0.5); p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.25
    r = p.add_run('· ' + text); _setfont(r, size)
    return p

def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd'); shd.set(qn('w:val'), 'clear'); shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)

def set_cell(cell, text, size=9, bold=False, color=None, align='left', fill=None):
    cell.text = ''
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(1); p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.line_spacing = 1.15
    p.alignment = {'left':WD_ALIGN_PARAGRAPH.LEFT,'center':WD_ALIGN_PARAGRAPH.CENTER}[align]
    for i, line in enumerate(text.split('\n')):
        if i > 0:
            p = cell.add_paragraph(); p.paragraph_format.space_after = Pt(1); p.paragraph_format.line_spacing = 1.15
        r = p.add_run(line); _setfont(r, size, bold, color)
    if fill: shade(cell, fill)

def make_table(doc, headers, rows, widths_cm, fills=None):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'
    t.autofit = False
    for j, h in enumerate(headers):
        set_cell(t.rows[0].cells[j], h, size=9, bold=True, color=RGBColor(0xFF,0xFF,0xFF), align='center', fill='14243B')
    for r_i, row in enumerate(rows):
        cells = t.add_row().cells
        for j, val in enumerate(row):
            al = 'left' if j == 0 or (len(val) > 12) else 'left'
            f = None
            if fills and fills(r_i) is not None:
                f = fills(r_i)
            set_cell(cells[j], val, size=9, fill=f)
    # column widths
    for j, w in enumerate(widths_cm):
        for row in t.rows:
            row.cells[j].width = Cm(w)
    return t

def landscape(doc):
    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = Mm(297), Mm(210)
    sec.left_margin = Cm(1.5); sec.right_margin = Cm(1.5)
    sec.top_margin = Cm(1.5); sec.bottom_margin = Cm(1.5)

def note(doc, text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(8)
    r = p.add_run(text); _setfont(r, 8.5, False, GREY)
    return p

